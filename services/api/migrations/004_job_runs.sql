-- Nightly job orchestration state. This is separate from
-- reporting.pipeline_runs, which audits the ETL's internal execution.
CREATE TABLE IF NOT EXISTS public.job_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_name text NOT NULL,
    target_date date NOT NULL,
    status text NOT NULL DEFAULT 'pending'
        CHECK (status IN ('pending', 'processing', 'completed', 'failed')),
    started_at timestamptz,
    finished_at timestamptz,
    error_message text,
    created_at timestamptz NOT NULL DEFAULT now()
);

-- Enforces one orchestration record per job and UTC target day, and supports
-- efficient idempotency/active-run lookups. `processing` is the job lock state.
CREATE UNIQUE INDEX IF NOT EXISTS ix_job_runs_job_name_target_date
    ON public.job_runs (job_name, target_date);
